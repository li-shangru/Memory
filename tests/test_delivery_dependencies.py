def test_companion_captures_unlisted_package_files_and_refuses_symlinks(
    tmp_path: Path,
) -> None:
    prefix = tmp_path / "prefix"
    item = synthetic_distribution(
        prefix, "memory-sqlcipher3", "1", {"sqlcipher3/__init__.py": b"# synthetic"}
    )
    package = Path(str(item.locate_file("sqlcipher3")))
    (package / "unlisted.so").write_bytes(b"synthetic extra")
    result = dp.companion_snapshot(item, prefix)
    assert (
        cast("dict[str, str]", result["files"])["unlisted.so"]
        == hashlib.sha256(b"synthetic extra").hexdigest()
    )
    (package / "unlisted.so").unlink()
    (package / "unlisted.so").symlink_to(package / "__init__.py")
    with pytest.raises(ValueError, match="dependency_symlink"):
        dp.companion_snapshot(item, prefix)


def test_file_replacement_during_hash_is_detected(
    tmp_path: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    prefix = tmp_path / "prefix"
    prefix.mkdir()
    target = prefix / "synthetic.bin"
    target.write_bytes(b"abc")
    original = os.read
    replaced = False

    def replace_after_read(descriptor: int, size: int) -> bytes:
        nonlocal replaced
        content = original(descriptor, size)
        if content and not replaced:
            replaced = True
            target.rename(prefix / "synthetic-old.bin")
            target.write_bytes(b"abc")
        return content

    monkeypatch.setattr(os, "read", replace_after_read)
    with pytest.raises(ValueError, match="dependency_file_changed"):
        dp._installed_hash(prefix, target)


@pytest.mark.parametrize(
    "package_member",
    ["sqlcipher3/uv_cache.json", "sqlcipher3/assets.dist-info/uv_cache.json"],
)
def test_uv_cache_is_only_installer_metadata_under_dist_info(
    tmp_path: Path, package_member: str
) -> None:
    prefix = tmp_path / "prefix"
    item = synthetic_distribution(
        prefix,
        "memory-sqlcipher3",
        "0.9.0",
        {
            "sqlcipher3/__init__.py": b"# synthetic companion\n",
            package_member: b"package-owned bytes",
            "memory_sqlcipher3-0.9.0.dist-info/uv_cache.json": b"installer bookkeeping",
        },
    )
    snapshot = dp.companion_snapshot(item, prefix)
    expected = dp.dependency_files(item, prefix)
    assert "memory_sqlcipher3-0.9.0.dist-info/uv_cache.json" not in expected
    assert package_member in expected
    assert snapshot["distribution_files"] == expected
    target = Path(str(item.locate_file(package_member)))
    target.write_bytes(b"altered package-owned bytes")
    with pytest.raises(ValueError, match=r"dependency_record_(size|hash)_drift"):
        dp.companion_snapshot(item, prefix)
