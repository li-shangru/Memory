def synthetic_distribution(
    prefix: Path,
    name: str,
    version: str,
    members: dict[str, bytes],
    *,
    algorithm: str = "sha256",
) -> PathDistribution:
    base = prefix / "lib/python3.14/site-packages"
    info = f"{name.replace('-', '_')}-{version}.dist-info"
    contents = {
        **members,
        f"{info}/METADATA": f"Metadata-Version: 2.4\nName: {name}\nVersion: {version}\n".encode(),
        f"{info}/WHEEL": b"Wheel-Version: 1.0\nTag: py3-none-any\n",
        f"{info}/INSTALLER": b"synthetic installer\n",
        f"{info}/REQUESTED": b"",
        f"{info}/direct_url.json": b'{"url":"synthetic://fixture"}',
    }
    record = io.StringIO(newline="")
    writer = csv.writer(record)
    for relative, content in contents.items():
        path = base / relative
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(content)
        digest = (
            base64.urlsafe_b64encode(hashlib.new(algorithm, content).digest())
            .decode()
            .rstrip("=")
        )
        writer.writerow([relative, f"{algorithm}={digest}", len(content)])
    writer.writerow([f"{info}/RECORD", "", ""])
    (base / info / "RECORD").write_text(record.getvalue())
    return PathDistribution(base / info)


def install_snapshot_fakes(
    prefix: Path, monkeypatch: pytest.MonkeyPatch
) -> tuple[PathDistribution, PathDistribution]:
    memory_dist = synthetic_distribution(
        prefix, "memory", "1.2.3", {"memory/__init__.py": b"__version__ = '1.2.3'\n"}
    )
    dependency = synthetic_distribution(
        prefix,
        "Synthetic-Dependency",
        "3.2.1",
        {
            "synthetic_dependency/__init__.py": "VALUE = '合成 package'\n".encode(),
            "synthetic_dependency/native.so": b"synthetic native\x00\xff",
            "../../../bin/synthetic-dependency": b"#!/synthetic/python\n",
            "synthetic_dependency/__pycache__/ignored.pyc": b"generated bytecode",
        },
    )
    companion = synthetic_distribution(
        prefix,
        "memory-sqlcipher3",
        "0.9.0",
        {
            "sqlcipher3/__init__.py": b"# synthetic companion; never imported\n",
            "sqlcipher3/dbapi2.py": b"# synthetic database facade\n",
            "sqlcipher3/_sqlite3.so": b"synthetic sqlcipher\x00\xff",
        },
    )
    module = ModuleType("memory")
    module.__file__ = str(memory_dist.locate_file("memory/__init__.py"))
    module.__dict__["__version__"] = "1.2.3"
    monkeypatch.setitem(sys.modules, "memory", module)
    monkeypatch.setattr(sys, "prefix", str(prefix))
    lookup = {"memory": memory_dist, "memory-sqlcipher3": companion}
    monkeypatch.setattr(dp, "distribution", lambda name: lookup[name])
    monkeypatch.setattr(
        dp, "distributions", lambda: [memory_dist, dependency, companion]
    )
    return dependency, companion


def test_snapshot_captures_dependency_and_companion_bytes_without_import(
    tmp_path: Path,
    monkeypatch: pytest.MonkeyPatch,
) -> None:
    prefix = tmp_path / "synthetic-install"
    dependency, companion = install_snapshot_fakes(prefix, monkeypatch)
    result = dp.snapshot()
    assert "dependency_files" in result, (
        "dependency versions alone cannot prove installed bytes"
    )
    files = cast("dict[str, dict[str, str]]", result["dependency_files"])
    assert set(files) == {"Synthetic-Dependency", "memory-sqlcipher3"}
    assert (
        files["Synthetic-Dependency"]["synthetic_dependency/native.so"]
        == hashlib.sha256(b"synthetic native\x00\xff").hexdigest()
    )
    assert "../../../bin/synthetic-dependency" in files["Synthetic-Dependency"]
    assert not any(
        "__pycache__" in key
        or key.endswith(("RECORD", "INSTALLER", "REQUESTED", "direct_url.json"))
        for inventory in files.values()
        for key in inventory
    )
    assert result["companion"] == {
        "version": companion.version,
        "origin": str(Path(str(companion.locate_file("sqlcipher3"))).resolve()),
        "metadata": companion.read_text("METADATA"),
        "files": dp.fingerprint(Path(str(companion.locate_file("sqlcipher3")))),
        "distribution_files": dp.dependency_files(companion, prefix),
    }
    assert (
        cast("dict[str, str]", result["dependencies"])["Synthetic-Dependency"]
        == dependency.version
    )


def _record_path(item: PathDistribution) -> Path:
    return Path(
        str(
            item.locate_file(
                next(member for member in item.files or [] if member.name == "RECORD")
            )
        )
    )


def change_record(
    item: PathDistribution,
    member: str,
    *,
    digest: str | None = None,
    size: str | None = None,
) -> None:
    path = _record_path(item)
    rows = list(csv.reader(io.StringIO(path.read_text())))
    for row in rows:
        if row[0] == member:
            if digest is not None:
                row[1] = digest
            if size is not None:
                row[2] = size
    output = io.StringIO(newline="")
    csv.writer(output).writerows(rows)
    path.write_text(output.getvalue())


@pytest.mark.parametrize(
    "mutation,code",
    [
        ("bytes", "dependency_record_hash_drift"),
        ("size", "dependency_record_size_drift"),
        ("missing", "dependency_path_unavailable"),
        ("hash_missing", "dependency_record_unsigned"),
        ("size_missing", "dependency_record_unsigned"),
        ("unsupported", "dependency_record_hash_unsupported"),
    ],
)
def test_dependency_bytes_and_record_claims_fail_closed(
    tmp_path: Path, mutation: str, code: str
) -> None:
    prefix = tmp_path / "prefix"
    item = synthetic_distribution(
        prefix, "Synthetic-Dependency", "1", {"synthetic/payload.py": b"abc"}
    )
    target = Path(str(item.locate_file("synthetic/payload.py")))
    if mutation == "bytes":
        target.write_bytes(b"xyz")
    elif mutation == "size":
        target.write_bytes(b"abcd")
    elif mutation == "missing":
        target.unlink()
    elif mutation == "hash_missing":
        change_record(item, "synthetic/payload.py", digest="")
    elif mutation == "size_missing":
        change_record(item, "synthetic/payload.py", size="")
    else:
        change_record(item, "synthetic/payload.py", digest="unsupported-hash=abc")
    with pytest.raises(ValueError, match=code):
        dp.dependency_files(item, prefix)


def test_supported_record_algorithm_is_verified_and_snapshot_uses_sha256(
    tmp_path: Path,
) -> None:
    prefix = tmp_path / "prefix"
    item = synthetic_distribution(
        prefix,
        "Synthetic-Dependency",
        "1",
        {"synthetic/payload.py": "合成字节".encode()},
        algorithm="sha512",
    )
    assert (
        dp.dependency_files(item, prefix)["synthetic/payload.py"]
        == hashlib.sha256("合成字节".encode()).hexdigest()
    )
    Path(str(item.locate_file("synthetic/payload.py"))).write_bytes("改变字节".encode())
    with pytest.raises(ValueError, match="dependency_record_hash_drift"):
        dp.dependency_files(item, prefix)


@pytest.mark.parametrize(
    "kind", ["file_symlink", "directory_symlink", "escape", "absolute", "fifo"]
)
def test_distribution_paths_cannot_escape_or_follow_links(
    tmp_path: Path, kind: str
) -> None:
    prefix = tmp_path / "prefix"
    item = synthetic_distribution(
        prefix, "Synthetic-Dependency", "1", {"synthetic/payload.py": b"abc"}
    )
    target = Path(str(item.locate_file("synthetic/payload.py")))
    if kind == "file_symlink":
        other = tmp_path / "synthetic-external.py"
        other.write_bytes(b"abc")
        target.unlink()
        target.symlink_to(other)
    elif kind == "directory_symlink":
        original = target.parent
        moved = original.with_name("synthetic-other")
        original.rename(moved)
        original.symlink_to(moved, target_is_directory=True)
    elif kind == "fifo":
        target.unlink()
        os.mkfifo(target)
    else:
        path = _record_path(item)
        entries = list(csv.reader(io.StringIO(path.read_text())))
        for entry in entries:
            if entry[0] == "synthetic/payload.py":
                entry[0] = (
                    "../../../../synthetic-external.py"
                    if kind == "escape"
                    else str(target)
                )
        output = io.StringIO(newline="")
        csv.writer(output).writerows(entries)
        path.write_text(output.getvalue())
    with pytest.raises(
        ValueError,
        match=r"dependency_(path_unavailable|path_escape|inventory_invalid|not_regular)",
    ):
        dp.dependency_files(item, prefix)


def test_complete_inventory_preserves_package_data_and_requires_record(
    tmp_path: Path,
) -> None:
    prefix = tmp_path / "prefix"
    item = synthetic_distribution(
        prefix,
        "Synthetic-Dependency",
        "1",
        {"synthetic/INSTALLER": b"real package data", "synthetic/data.json": b"{}"},
    )
    files = dp.dependency_files(item, prefix)
    assert "synthetic/INSTALLER" in files
    assert "synthetic/data.json" in files
    assert any(key.endswith("/METADATA") for key in files)
    _record_path(item).unlink()
    with pytest.raises(ValueError, match="dependency_inventory_missing"):
        dp.dependency_files(item, prefix)


